void RCC_GPIOA_ClockEnable(void)
{
    RCC_AHB1ENR_REG |= (1UL << RCC_AHB1ENR_GPIOAEN_BIT);
}

void RCC_GPIOD_ClockEnable(void)
{
    RCC_AHB1ENR_REG |= (1UL << RCC_AHB1ENR_GPIODEN_BIT);
}

